create or replace function private.is_account_active()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles profile
    where profile.id = (select auth.uid())
      and profile.account_status = 'active'
  );
$$;

revoke all on function private.is_account_active() from public, anon;
grant execute on function private.is_account_active() to authenticated, service_role;

create or replace function private.guard_profile_account_control()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (
    new.account_status is distinct from old.account_status
    or new.suspended_at is distinct from old.suspended_at
    or new.suspension_reason is distinct from old.suspension_reason
    or new.suspended_by is distinct from old.suspended_by
  ) and not (
    (select private.is_app_admin())
    or coalesce(current_setting('request.jwt.claim.role', true), '') = 'service_role'
  ) then
    raise exception 'Only an administrator can change account access.';
  end if;
  return new;
end;
$$;

drop trigger if exists profiles_guard_account_control on public.profiles;
create trigger profiles_guard_account_control
before update on public.profiles
for each row execute function private.guard_profile_account_control();

create or replace function private.guard_profile_role_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.role is distinct from old.role and not (
    (select private.is_app_admin())
    or coalesce(current_setting('request.jwt.claim.role', true), '') = 'service_role'
  ) then
    raise exception 'Only an administrator can change account roles.';
  end if;
  return new;
end;
$$;

do $policy_setup$
declare
  target record;
begin
  for target in
    select namespace.nspname as schema_name, class.relname as table_name
    from pg_class class
    join pg_namespace namespace on namespace.oid = class.relnamespace
    where class.relkind in ('r', 'p')
      and class.relrowsecurity
      and namespace.nspname = 'public'
      and class.relname <> 'app_takeover_notices'
  loop
    execute format(
      'drop policy if exists %I on %I.%I',
      'Active accounts use OG Vibes', target.schema_name, target.table_name
    );
    execute format(
      'create policy %I on %I.%I as restrictive for all to authenticated using ((select private.is_account_active())) with check ((select private.is_account_active()))',
      'Active accounts use OG Vibes', target.schema_name, target.table_name
    );
  end loop;
end
$policy_setup$;

drop policy if exists "Active accounts use OG Vibes" on storage.objects;
